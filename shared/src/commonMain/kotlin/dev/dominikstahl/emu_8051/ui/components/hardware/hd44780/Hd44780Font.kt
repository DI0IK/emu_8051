object Hd44780Font {
    val CGROM: ByteArray by lazy {
        ByteArray(256 * 8).also { data ->
            for ((code, rows) in FONT_MAP) {
                for ((i, row) in rows.withIndex()) {
                    data[code * 8 + i] = row.toByte()
                }
            }
        }
    }

    fun getCharPattern(code: Int, cgram: ByteArray? = null): ByteArray {
        return when {
            code in 0..7 && cgram != null && cgram.size >= 64 -> {
                val offset = code * 8
                cgram.sliceArray(offset until offset + 8)
            }
            code in 0..255 -> {
                val offset = code * 8
                if (offset + 8 <= CGROM.size) CGROM.sliceArray(offset until offset + 8)
                else ByteArray(8)
            }
            else -> ByteArray(8)
        }
    }

